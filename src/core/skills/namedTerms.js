/**
 * 解析 named 引用。
 * @param {string} ref 热区/标记携带的引用名（可含尾缀数字，如「衰败2」）
 * @param {object} [opts] agent: true = headless/LLM 口径（程序化细则），缺省玩家口径
 * @returns {{ name:string, param:number|null, color:string, text:string } | null}
 *   未知术语返回 null（调用方回落通用呈现）
 */
export function getNamedTerm(ref, { agent = false } = {}) {
  const m = String(ref ?? '').match(/^(.+?)(\d+)$/);
  const name = m ? m[1] : String(ref ?? '');
  const def = TERMS[name];
  if (!def) return null;
  const param = m ? parseInt(m[2], 10) : null;
  const describe = agent && def.agent ? def.agent : def.describe;
  return { name, param, color: def.color, text: describe(param) };
}

/**
 * 全部词条（headless 文本界面等只读展示用；顺序即声明序）。
 * opts.agent = true 时返回 agent 口径——headless 的 terms 视图用（LLM 玩家需要
 * 程序化细则：触发时机/判定口径/不生效情形，防规则误读；缺 agent 字段的词条
 * 回落玩家版）。
 */
export function listNamedTerms({ agent = false } = {}) {
  return Object.entries(TERMS).map(([name, def]) => ({
    name,
    text: (agent && def.agent ? def.agent : def.describe)(null),
  }));
}
